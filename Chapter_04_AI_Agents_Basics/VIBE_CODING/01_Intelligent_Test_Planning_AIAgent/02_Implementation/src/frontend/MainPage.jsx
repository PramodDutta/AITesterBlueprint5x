import React, { useMemo, useState } from 'react';
import { marked } from 'marked';
import { api } from './api.js';

// Escape raw HTML before rendering so Jira/LLM text cannot inject markup.
const toHtml = (md) => marked.parse(md.replace(/</g, '&lt;'), { gfm: true });

export default function MainPage({ config }) {
  const [issueKey, setIssueKey] = useState('');
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState('');
  const [result, setResult] = useState(null);
  const html = useMemo(() => (result ? toHtml(result.plan) : ''), [result]);

  async function submit(e) {
    e.preventDefault();
    if (loading) return;
    const key = issueKey.trim();
    if (!key) return setError('Enter a Jira issue ID, for example QA-123.');
    setLoading(true);
    setError('');
    try {
      setResult(await api('/api/generate', { issueKey: key, config }));
    } catch (err) {
      setError(err.message);
    } finally {
      setLoading(false);
    }
  }

  return (
    <main className="page">
      <h1 className="title">Main page</h1>
      <section className="box reply" aria-live="polite">
        {loading && <p className="state">Fetching {issueKey.trim().toUpperCase()} from Jira and generating the test plan…</p>}
        {!loading && !result && !error && <p className="state">Reply with Test Plan will appear here. Enter a Jira ticket below.</p>}
        {!loading && error && <p className="state error" role="alert">{error}</p>}
        {!loading && result && (
          <>
            <div className="meta">
              Source: <a href={result.source.url} target="_blank" rel="noreferrer">{result.source.key}</a>
              {' · '}{result.source.issueType} · {result.source.status} · generated by {result.provider} ({result.model})
            </div>
            {result.warnings.map((w) => <p key={w} className="warn">⚠ {w}</p>)}
            <article className="plan" dangerouslySetInnerHTML={{ __html: html }} />
          </>
        )}
      </section>
      <form className="box prompt" onSubmit={submit}>
        <input
          aria-label="Prompt (JIRA Ticket)"
          placeholder="Prompt (JIRA Ticket), e.g. QA-123"
          value={issueKey}
          onChange={(e) => setIssueKey(e.target.value)}
          disabled={loading}
        />
        <button type="submit" disabled={loading}>{loading ? 'Generating…' : 'Generate'}</button>
      </form>
    </main>
  );
}
